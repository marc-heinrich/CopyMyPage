-- CMP #177. Additive, version-independent installer migration. Financial records are retained on uninstall.
CREATE TABLE IF NOT EXISTS `#__copymypage_payment_attempts` (
  `id` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `booking_id` INT UNSIGNED NOT NULL,
  `cart_id` INT UNSIGNED NOT NULL,
  `owner_id` INT UNSIGNED NOT NULL,
  `provider_id` VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `provider_account_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `sandbox` TINYINT UNSIGNED NOT NULL,
  `snapshot_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `expected_amount` DECIMAL(15,2) NOT NULL,
  `expected_currency` CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `expected_payee` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `return_base_uri` VARCHAR(512) NOT NULL,
  `create_key` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `capture_key` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `create_payload_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `order_id` VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `capture_id` VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `state` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'prepared',
  `provider_status` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `provider_evidence` MEDIUMTEXT DEFAULT NULL,
  `manual_reason` VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `lease_id` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `lease_expires` DATETIME(6) DEFAULT NULL,
  `create_started` DATETIME(6) DEFAULT NULL,
  `create_safe_until` DATETIME(6) DEFAULT NULL,
  `capture_started` DATETIME(6) DEFAULT NULL,
  `captured_at` DATETIME(6) DEFAULT NULL,
  `finalized_at` DATETIME(6) DEFAULT NULL,
  `retry_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `version` INT UNSIGNED NOT NULL DEFAULT 0,
  `created` DATETIME(6) NOT NULL,
  `modified` DATETIME(6) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_cmp_payment_booking` (`booking_id`),
  UNIQUE KEY `uq_cmp_payment_create` (`create_key`),
  UNIQUE KEY `uq_cmp_payment_capture` (`capture_key`),
  UNIQUE KEY `uq_cmp_payment_order` (`provider_id`,`order_id`),
  UNIQUE KEY `uq_cmp_payment_capture_id` (`provider_id`,`capture_id`),
  KEY `idx_cmp_payment_recovery` (`state`,`modified`),
  CONSTRAINT `#__cmp_payment_amount` CHECK (`expected_amount` > 0),
  CONSTRAINT `#__cmp_payment_keys` CHECK (`create_key` <> `capture_key`),
  CONSTRAINT `#__cmp_payment_state` CHECK (`state` IN ('prepared','creating','create_unknown','order_observed','order_created','capturing','capture_unknown','captured','finalizing','finalize_failed','finalized','cancel_check','cancel_unknown','cancelled','failed','manual'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `#__copymypage_mail_outbox` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `dedupe_key` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `booking_id` INT UNSIGNED NOT NULL,
  `attempt_id` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `snapshot_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `kind` VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `state` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'ready',
  `sender` VARCHAR(254) NOT NULL,
  `recipients` TEXT NOT NULL,
  `mime` LONGBLOB NOT NULL,
  `lease_id` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `lease_expires` DATETIME(6) DEFAULT NULL,
  `attempts` INT UNSIGNED NOT NULL DEFAULT 0,
  `last_error` VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `sent_at` DATETIME(6) DEFAULT NULL,
  `created` DATETIME(6) NOT NULL,
  `modified` DATETIME(6) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_cmp_outbox_job` (`dedupe_key`),
  KEY `idx_cmp_outbox_dispatch` (`state`,`modified`),
  KEY `idx_cmp_outbox_attempt` (`attempt_id`),
  CONSTRAINT `#__cmp_outbox_attempt` FOREIGN KEY (`attempt_id`) REFERENCES `#__copymypage_payment_attempts` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `#__cmp_outbox_state` CHECK (`state` IN ('ready','sending','retryable','sent','unknown'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
